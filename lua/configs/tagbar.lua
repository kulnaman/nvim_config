-- ~/.config/nvim/lua/config/tagbar.lua

-- Tagbar window width
vim.g.tagbar_width = 35

-- Auto-close tagbar after jumping to a tag
vim.g.tagbar_autoclose = 0

-- Auto-focus tagbar when opened
vim.g.tagbar_autofocus = 1

-- Sort tags by name (0 = sort by file order)
vim.g.tagbar_sort = 0

-- Show line numbers in tagbar
vim.g.tagbar_show_linenumbers = 1

-- Show tag visibility symbols (+, -, #)
vim.g.tagbar_show_visibility = 1

-- Compact display (no blank lines between top-level scopes)
vim.g.tagbar_compact = 1

-- Indent size
vim.g.tagbar_indent = 2

-- Auto-preview tag on cursor move
vim.g.tagbar_autopreview = 0

-- Position: open on the right
vim.g.tagbar_position = "botright vertical"

